  function getCutoutGlyphPolygons(ch) {
    const def = CUTOUT_DEFS[ch];
    if (!def) return [];
    const out = [];
    if (def.polys) {
      for (let i = 0; i < def.polys.length; i++) out.push(ensureCW2D(def.polys[i]));
    }
    if (def.strokes) {
      for (let i = 0; i < def.strokes.length; i++) out.push(thickenPolylineCW(def.strokes[i], 0.092));
    }
    return out;
  }

  function layoutCutoutGreeting(rawText, sizeMm) {
    const text = sanitizeGreetingText(rawText, 24);
    const s = Math.max(6, Number(sizeMm) || 13);
    const gapMm = Math.max(1.4, s * 0.18);
    const items = [];
    let cursorX = 0;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      const def = CUTOUT_DEFS[ch] || GLYPHS[ch];
      if (!def) continue;
      const boxW = Math.max(s * 0.20, s * def.w);
      const holesNorm = getCutoutGlyphPolygons(ch);
      items.push({
        ch,
        xStart: cursorX,
        boxW,
        holesNorm
      });
      cursorX += boxW + (i < text.length - 1 ? gapMm : 0);
    }
    const totalW = cursorX;
    for (let i = 0; i < items.length; i++) {
      items[i].xStart -= totalW * 0.5;
    }
    return {
      text,
      sizeMm: s,
      gapMm,
      totalWidthMm: totalW,
      items
    };
  }

